import re

import jieba

from langchain_core.documents import Document
from rank_bm25 import BM25Okapi


# ============================================================
# 1. 报警代码正则
#
# 例如：
# E-103
# E-104
#
# 目的：
# 不让 jieba 把 E-103 拆开
# ============================================================

ALARM_CODE_PATTERN = re.compile(
    r"(?i)(?<![a-zA-Z0-9])E-\d{3}(?![a-zA-Z0-9])"
)


# ============================================================
# 2. 设备编号正则
#
# 例如：
# RB-001
# RB-002
#
# 目的：
# 不让设备编号被拆成 rb 和 001
# ============================================================

DEVICE_ID_PATTERN = re.compile(
    r"(?i)(?<![a-zA-Z0-9])RB-\d{3}(?![a-zA-Z0-9])"
)


# ============================================================
# 3. 通用 Token 提取规则
#
# 优先识别：
#
# 1. E-103 这种报警代码
# 2. RB-001 这种设备编号
# 3. 中文文本
# 4. 英文 / 数字 / 下划线
#
# 注意：
# 报警代码和设备编号必须写在普通英文数字规则前面，
# 否则可能先被普通规则拆开。
# ============================================================

TOKEN_PATTERN = re.compile(
    r"(?i)(?<![a-zA-Z0-9])E-\d{3}(?![a-zA-Z0-9])"
    r"|(?<![a-zA-Z0-9])RB-\d{3}(?![a-zA-Z0-9])"
    r"|[\u4e00-\u9fff]+"
    r"|[a-zA-Z0-9_]+"
)


# ============================================================
# 4. 分词函数
# ============================================================

def tokenize(
    text: str,
) -> list[str]:

    # --------------------------------------------------------
    # 4.1 清理文本
    #
    # strip()
    # 去掉文本前后的空格、换行等
    #
    # lower()
    # 将英文统一转成小写
    #
    # 例如：
    # E-103 → e-103
    # RB-001 → rb-001
    # --------------------------------------------------------

    text = text.strip().lower()

    # 如果文本为空，
    # 直接返回空列表
    if not text:
        return []

    # 保存最终分词结果
    tokens: list[str] = []

    # --------------------------------------------------------
    # 4.2 使用 TOKEN_PATTERN
    #     从文本中逐个找出有效片段
    # --------------------------------------------------------

    for match in TOKEN_PATTERN.finditer(
        text
    ):

        part = match.group()

        # ----------------------------------------------------
        # 4.3 如果当前片段是报警代码
        #     或设备编号
        #
        # 直接完整保留
        #
        # 例如：
        # e-103
        # rb-001
        # ----------------------------------------------------

        if (
            ALARM_CODE_PATTERN.fullmatch(part)
            or DEVICE_ID_PATTERN.fullmatch(part)
        ):

            tokens.append(part)

            continue

        # ----------------------------------------------------
        # 4.4 如果当前片段是纯中文
        #
        # 使用 jieba 继续分词
        # ----------------------------------------------------

        if re.fullmatch(
            r"[\u4e00-\u9fff]+",
            part,
        ):

            for word in jieba.cut(part):

                word = word.strip()

                if word:
                    tokens.append(word)

            continue

        # ----------------------------------------------------
        # 4.5 普通英文、数字、下划线
        #
        # 直接作为一个 Token 保存
        # ----------------------------------------------------

        tokens.append(part)

    # --------------------------------------------------------
    # 4.6 返回最终 Token 列表
    # --------------------------------------------------------

    return tokens


# ============================================================
# 5. BM25 检索器
# ============================================================

class BM25Retriever:

    # ========================================================
    # 5.1 初始化 BM25 Retriever
    #
    # 这个方法在：
    #
    # retriever = BM25Retriever(documents)
    #
    # 执行时自动调用。
    #
    # 它的主要任务不是“搜索”，
    # 而是“建立 BM25 索引”。
    # ========================================================

    def __init__(
        self,
        documents: list[Document],
    ):

        # ----------------------------------------------------
        # 保存原始 Chunk Documents
        #
        # 后面 BM25 找到某个索引以后，
        # 还需要通过这个列表找回真正的：
        #
        # page_content
        # metadata
        # ----------------------------------------------------

        self.documents = documents

        # ----------------------------------------------------
        # 将每一个 Chunk 的正文进行分词
        #
        # documents:
        #
        # [
        #     Document("E-103 电机过热报警..."),
        #     Document("E-104 位置偏差异常..."),
        # ]
        #
        # ↓
        #
        # tokenized_corpus:
        #
        # [
        #     ["e-103", "电机", "过热", "报警", ...],
        #     ["e-104", "位置", "偏差", "异常", ...],
        # ]
        # ----------------------------------------------------

        self.tokenized_corpus = [
            tokenize(
                document.page_content
            )
            for document in documents
        ]

        # ----------------------------------------------------
        # 根据整个语料库建立 BM25 索引
        #
        # 如果 documents 是空的，
        # 就不创建 BM25Okapi。
        # ----------------------------------------------------

        self.bm25 = (
            BM25Okapi(
                self.tokenized_corpus
            )
            if self.tokenized_corpus
            else None
        )

    # ========================================================
    # 5.2 在线检索
    #
    # 输入：
    #
    # query
    # top_k
    #
    # 输出：
    #
    # BM25 排名前 top_k 的 Chunk
    # ========================================================

    def retrieve(
        self,
        query: str,
        top_k: int = 5,
    ) -> list[dict]:

        # ----------------------------------------------------
        # 1. 清理 Query
        # ----------------------------------------------------

        query = query.strip()

        # ----------------------------------------------------
        # 2. Query 不能为空
        # ----------------------------------------------------

        if not query:
            raise ValueError(
                "检索 Query 不能为空"
            )

        # ----------------------------------------------------
        # 3. top_k 必须大于 0
        # ----------------------------------------------------

        if top_k <= 0:
            raise ValueError(
                "top_k 必须大于 0"
            )

        # ----------------------------------------------------
        # 4. 如果没有 BM25 索引
        #
        # 说明没有任何文档可以检索
        # ----------------------------------------------------

        if self.bm25 is None:
            return []

        # ----------------------------------------------------
        # 5. 对用户 Query 使用完全相同的 tokenize()
        #
        # 例如：
        #
        # "E-103 报警原因"
        #
        # ↓
        #
        # ["e-103", "报警", "原因"]
        # ----------------------------------------------------

        query_tokens = tokenize(
            query
        )

        # ----------------------------------------------------
        # 6. BM25 给知识库中的所有 Chunk 打分
        #
        # 假设有 4 个 Chunk：
        #
        # scores =
        # [
        #     0.2,
        #     0.5,
        #     5.8,
        #     1.7,
        # ]
        #
        # scores[2]
        # 就对应 documents[2]
        # ----------------------------------------------------

        scores = self.bm25.get_scores(
            query_tokens
        )

        # ----------------------------------------------------
        # 7. 根据 BM25 Score
        #    对文档索引进行从高到低排序
        #
        # 假设：
        #
        # scores =
        # [0.2, 0.5, 5.8, 1.7]
        #
        # 排序后：
        #
        # ranked_indices =
        # [2, 3, 1, 0]
        # ----------------------------------------------------

        ranked_indices = sorted(
            range(len(scores)),
            key=lambda index: scores[index],
            reverse=True,
        )

        # ----------------------------------------------------
        # 8. 保存最终检索结果
        # ----------------------------------------------------

        results: list[dict] = []

        # ----------------------------------------------------
        # 9. 只处理排名前 top_k 的文档
        # ----------------------------------------------------

        for index in ranked_indices[:top_k]:

            # 获取当前 Chunk 的 BM25 分数
            score = float(
                scores[index]
            )

            # 当前第一版策略：
            # 不返回 BM25 分数 <= 0 的结果
            if score <= 0:
                continue

            # ------------------------------------------------
            # 通过 index 找回原始 Chunk Document
            # ------------------------------------------------

            document = self.documents[
                index
            ]

            # 获取 metadata
            metadata = document.metadata

            # ------------------------------------------------
            # 10. 转换成统一检索结果结构
            # ------------------------------------------------

            result = {
                "id": metadata[
                    "chunk_id"
                ],
                "score": score,
                "content": (
                    document.page_content
                ),
                "source": metadata.get(
                    "source"
                ),
                "section_number": metadata.get(
                    "section_number"
                ),
                "section_title": metadata.get(
                    "section_title"
                ),
                "page_start": metadata.get(
                    "page_start"
                ),
                "page_end": metadata.get(
                    "page_end"
                ),
                "alarm_code": metadata.get(
                    "alarm_code"
                ),
                "chunk_index": metadata.get(
                    "chunk_index"
                ),
            }

            # ------------------------------------------------
            # 11. 保存当前结果
            # ------------------------------------------------

            results.append(
                result
            )

        # ----------------------------------------------------
        # 12. 返回最终 BM25 Top-K
        # ----------------------------------------------------

        return results